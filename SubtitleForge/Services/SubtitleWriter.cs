using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using SubtitleForge.Models;

namespace SubtitleForge.Services
{
    public class AssStyleOptions
    {
        public string FontName { get; set; } = "Segoe UI";

        public int FontSize { get; set; } = 20;

        public int OutlineThickness { get; set; } = 1;

        public int MarginVertical { get; set; } = 40;
    }

    /// <summary>
    /// Writes cues as SRT, WebVTT and ASS (Advanced SubStation Alpha).
    /// </summary>
    public static class SubtitleWriter
    {
        private static readonly Encoding FileEncoding = new UTF8Encoding(false);

        public static string ToSrt(IEnumerable<SubtitleCue> cues)
        {
            StringBuilder builder = new StringBuilder();
            int index = 1;

            foreach (SubtitleCue cue in cues)
            {
                builder.Append(index.ToString(CultureInfo.InvariantCulture)).AppendLine();
                builder.Append(FormatTimestamp(cue.Start, ','))
                    .Append(" --> ")
                    .Append(FormatTimestamp(cue.End, ','))
                    .AppendLine();
                builder.AppendLine(NormalizeLineEndings(cue.Text));
                builder.AppendLine();
                index++;
            }

            return builder.ToString();
        }

        public static string ToVtt(IEnumerable<SubtitleCue> cues)
        {
            StringBuilder builder = new StringBuilder();
            builder.AppendLine("WEBVTT");
            builder.AppendLine();

            foreach (SubtitleCue cue in cues)
            {
                builder.Append(FormatTimestamp(cue.Start, '.'))
                    .Append(" --> ")
                    .Append(FormatTimestamp(cue.End, '.'))
                    .AppendLine();
                builder.AppendLine(NormalizeLineEndings(cue.Text));
                builder.AppendLine();
            }

            return builder.ToString();
        }

        public static string ToAss(IEnumerable<SubtitleCue> cues, AssStyleOptions style)
        {
            StringBuilder builder = new StringBuilder();

            builder.AppendLine("[Script Info]");
            builder.AppendLine("; Generated by SubtitleForge");
            builder.AppendLine("ScriptType: v4.00+");
            builder.AppendLine("WrapStyle: 2");
            builder.AppendLine("ScaledBorderAndShadow: yes");
            builder.AppendLine("PlayResX: 853");
            builder.AppendLine("PlayResY: 480");
            builder.AppendLine();

            builder.AppendLine("[V4+ Styles]");
            builder.AppendLine("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding");
            builder.AppendLine(
                "Style: Default,"
                + SanitizeStyleText(style.FontName)
                + ","
                + style.FontSize.ToString(CultureInfo.InvariantCulture)
                + ",&H00FFFFFF,&H000000FF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,"
                + Math.Max(0, style.OutlineThickness).ToString("0.#", CultureInfo.InvariantCulture)
                + ",0.5,2,40,40,"
                + Math.Max(0, style.MarginVertical).ToString(CultureInfo.InvariantCulture)
                + ",1");
            builder.AppendLine();

            builder.AppendLine("[Events]");
            builder.AppendLine("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text");

            foreach (SubtitleCue cue in cues)
            {
                builder.Append("Dialogue: 0,")
                    .Append(FormatAssTimestamp(cue.Start))
                    .Append(',')
                    .Append(FormatAssTimestamp(cue.End))
                    .Append(",Default,,0,0,0,,")
                    .AppendLine(EscapeAssText(cue.Text));
            }

            return builder.ToString();
        }

        public static void SaveSrt(string path, IEnumerable<SubtitleCue> cues)
        {
            File.WriteAllText(path, ToSrt(cues), FileEncoding);
        }

        public static void SaveVtt(string path, IEnumerable<SubtitleCue> cues)
        {
            File.WriteAllText(path, ToVtt(cues), FileEncoding);
        }

        public static void SaveAss(string path, IEnumerable<SubtitleCue> cues, AssStyleOptions style)
        {
            File.WriteAllText(path, ToAss(cues, style), FileEncoding);
        }

        public static string FormatTimestamp(TimeSpan value, char millisecondSeparator)
        {
            if (value < TimeSpan.Zero)
            {
                value = TimeSpan.Zero;
            }

            return string.Format(
                CultureInfo.InvariantCulture,
                "{0:00}:{1:00}:{2:00}{3}{4:000}",
                (int)value.TotalHours,
                value.Minutes,
                value.Seconds,
                millisecondSeparator,
                value.Milliseconds);
        }

        public static string FormatAssTimestamp(TimeSpan value)
        {
            if (value < TimeSpan.Zero)
            {
                value = TimeSpan.Zero;
            }

            int centiseconds = (int)Math.Round(value.Milliseconds / 10.0, MidpointRounding.AwayFromZero);
            int seconds = value.Seconds;
            int minutes = value.Minutes;
            int hours = (int)value.TotalHours;

            if (centiseconds >= 100)
            {
                centiseconds -= 100;
                seconds++;
            }

            if (seconds >= 60)
            {
                seconds -= 60;
                minutes++;
            }

            if (minutes >= 60)
            {
                minutes -= 60;
                hours++;
            }

            return string.Format(
                CultureInfo.InvariantCulture,
                "{0}:{1:00}:{2:00}.{3:00}",
                hours,
                minutes,
                seconds,
                centiseconds);
        }

        private static string NormalizeLineEndings(string text)
        {
            return (text ?? string.Empty).Replace("\r\n", "\n").Replace("\r", "\n");
        }

        private static string EscapeAssText(string text)
        {
            string normalized = NormalizeLineEndings(text);
            normalized = normalized.Replace("\\", "＼");
            normalized = normalized.Replace("{", "(").Replace("}", ")");
            normalized = normalized.Replace("\n", "\\N");
            return normalized.Trim();
        }

        private static string SanitizeStyleText(string text)
        {
            if (string.IsNullOrWhiteSpace(text))
            {
                return "Segoe UI";
            }

            return text.Replace(",", " ").Trim();
        }
    }
}
